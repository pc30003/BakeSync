export type ShiftType = "MORNING" | "AFTERNOON" | "EVENING" | "OVERNIGHT";

export type ProductionBatchStatus =
  | "SCHEDULED"
  | "IN_PROGRESS"
  | "COMPLETED"
  | "CANCELLED"
  | "BLOCKED";     // blocked due to ingredient shortfall

export type ChecklistItemStatus = "PENDING" | "IN_PROGRESS" | "DONE" | "SKIPPED";

export interface ChecklistItem {
  id: string;
  batchId: string;
  stageId: string | null;
  order: number;
  description: string;
  status: ChecklistItemStatus;
  completedBy: string | null;   // userId
  completedAt: Date | null;
  notes: string | null;
}

export interface ProductionBatch {
  id: string;
  bakeryId: string;
  scheduleId: string;
  recipeId: string;
  recipeName: string;
  shiftType: ShiftType;
  status: ProductionBatchStatus;
  quantity: number;             // number of recipe-yield units to produce
  scaleFactor: number;          // how many times the base recipe is multiplied
  plannedStartTime: Date;
  plannedEndTime: Date;
  actualStartTime: Date | null;
  actualEndTime: Date | null;
  assignedStaffIds: string[];
  ovenSlots: number;            // how many oven slots this batch needs
  checklist: ChecklistItem[];
  notes: string | null;
}

export interface ProductionSchedule {
  id: string;
  bakeryId: string;
  scheduleDate: Date;
  shiftType: ShiftType;
  isAutoGenerated: boolean;
  isApproved: boolean;
  approvedBy: string | null;
  approvedAt: Date | null;
  batches: ProductionBatch[];
  totalOvenUtilizationPercent: number;
  aiNotes: string | null;       // reasoning notes from the AI agent
  createdAt: Date;
  updatedAt: Date;
}

export interface ShiftChecklist {
  scheduleId: string;
  shiftType: ShiftType;
  scheduleDate: Date;
  batches: Array<{
    batchId: string;
    recipeName: string;
    quantity: number;
    plannedStartTime: Date;
    items: ChecklistItem[];
  }>;
}

export interface OvenCapacityBlock {
  id: string;
  bakeryId: string;
  startTime: Date;
  endTime: Date;
  batchId: string | null;
  isBlocked: boolean;           // manual block (maintenance, etc.)
  notes: string | null;
}

export interface AgentScheduleRequest {
  bakeryId: string;
  targetDate: Date;
  shiftType?: ShiftType;
  forceRegenerate?: boolean;
}

export interface AgentScheduleResult {
  schedule: ProductionSchedule;
  shortfalls: Array<{
    ingredientId: string;
    ingredientName: string;
    shortfallGrams: number;
  }>;
  warnings: string[];
  processingMs: number;
}
