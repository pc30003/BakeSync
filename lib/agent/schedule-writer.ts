/**
 * lib/agent/schedule-writer.ts
 *
 * Takes the AgentSchedulePlan from the planner and persists it to the database:
 *  1. Creates/updates ProductionSchedule
 *  2. Creates ProductionBatch rows with ovenSlots + scaleFactor
 *  3. Creates ChecklistItem rows from checklistSteps
 *  4. Creates ProcurementRecommendation rows for any ingredient shortfalls
 *  5. Creates AgentAlert rows for shortfalls, expiring lots, and warnings
 *
 * Does NOT deduct stock here — stock is deducted when a batch is marked
 * IN_PROGRESS by floor staff so the numbers stay accurate in real-time.
 */

import { db } from "@/lib/db";
import { format } from "date-fns";
import type { AgentBakeryContext, AgentSchedulePlan, AgentRunResult } from "./types";

export async function writeSchedule(
  context: AgentBakeryContext,
  plan: AgentSchedulePlan,
  agentActionId: string,
  startedAt: Date
): Promise<AgentRunResult> {
  const { bakeryId, targetDate, shiftType } = context;

  // Convert target date string back to a Date (midnight UTC)
  const scheduleDate = new Date(`${targetDate}T00:00:00.000Z`);

  const shortfalls: AgentRunResult["shortfalls"] = [];

  try {
    // ── 1. Upsert the ProductionSchedule ────────────────────────────────────
    // Completed runs are snapshotted to ProductionRunHistory and their live row
    // is deleted on close, so the (date, shift) slot is always free to (re)use.
    const schedule = await db.productionSchedule.upsert({
      where: {
        bakeryId_scheduleDate_shiftType: {
          bakeryId,
          scheduleDate,
          shiftType: shiftType as any,
        },
      },
      update: {
        isAutoGenerated:             true,
        isApproved:                  false,  // reset approval on regeneration
        isClosed:                    false,  // a freshly generated plan is active, never archived
        approvedById:                null,
        approvedAt:                  null,
        closedAt:                    null,
        totalOvenUtilizationPercent: plan.ovenUtilizationPercent,
        aiNotes:                     plan.aiNotes,
        updatedAt:                   new Date(),
      },
      create: {
        bakeryId,
        scheduleDate,
        shiftType:                   shiftType as any,
        isAutoGenerated:             true,
        isApproved:                  false,
        totalOvenUtilizationPercent: plan.ovenUtilizationPercent,
        aiNotes:                     plan.aiNotes,
      },
    });

    // Delete any existing batches for this schedule (clean regeneration)
    await db.productionBatch.deleteMany({ where: { scheduleId: schedule.id } });

    // Build a lookup map: recipeId AND recipe name → actual DB recipeId
    const recipeMap = new Map<string, string>();
    for (const r of context.recipes) {
      recipeMap.set(r.recipeId, r.recipeId);
      recipeMap.set(r.name.toLowerCase(), r.recipeId);
    }

    // ── STOCK-FEASIBILITY GUARDRAIL ──────────────────────────────────────────
    // The AI is *told* to scale down for low stock, but that's a soft instruction
    // and not guaranteed. Here we ENFORCE it deterministically: we track the real
    // remaining stock of every ingredient and, per batch (in plan order), clamp
    // the batch's scaleFactor/quantity down to what stock can actually cover —
    // accounting for the recipe's wastage buffer and for earlier batches in the
    // same run that already consumed shared ingredients. This makes it impossible
    // for a generated plan to schedule more than physically exists.
    const remainingStock = new Map<string, number>();
    for (const s of context.stockLevels) {
      remainingStock.set(s.ingredientId, Number(s.stockGrams));
    }
    // Collect deterministic (real-stock) shortfalls detected by the clamp.
    const stockShortfalls: AgentRunResult["shortfalls"] = [];

    // ── 2. Create batches + checklists ───────────────────────────────────────
    for (const batch of plan.batches) {
      // Resolve recipe ID — AI might return the actual ID or the recipe name
      const resolvedRecipeId = recipeMap.get(batch.recipeId)
        ?? recipeMap.get(batch.recipeName?.toLowerCase() ?? "")
        ?? null;

      if (!resolvedRecipeId) {
        // Skip batches with unrecognized recipes
        continue;
      }

      // Get the recipe's ingredients (needed for the feasibility clamp below)
      const recipeData = context.recipes.find((r) => r.recipeId === resolvedRecipeId);
      const recipeIngredients = recipeData?.ingredients ?? [];
      const wastageMult = 1 + (Number(recipeData?.wastageBufferPercent ?? 0) / 100);

      const aiScale = Number(batch.scaleFactor) || 1;
      const aiQty   = Math.round(batch.quantity);

      // Max scale each ingredient's remaining stock can support (per-unit need
      // includes the wastage buffer). Ingredients with base 0 are unconstrained.
      let feasibleScale = aiScale;
      let limitingName: string | null = null;
      for (const ri of recipeIngredients) {
        const perUnit = ri.quantityGrams * wastageMult;
        if (perUnit <= 0) continue;
        const have = remainingStock.get(ri.ingredientId) ?? 0;
        const maxScaleForIng = have / perUnit;
        if (maxScaleForIng < feasibleScale) {
          feasibleScale = maxScaleForIng;
          limitingName  = ri.name;
        }
      }
      // Clamp to [0, aiScale]; round down to 3 dp (schema is Decimal(8,3)).
      feasibleScale = Math.max(0, Math.min(aiScale, Math.floor(feasibleScale * 1000) / 1000));

      // If the plan wanted more than stock allows, record the real shortfall
      // (what the AI intended to make minus what stock can actually cover) for
      // the limiting ingredient(s), so procurement is raised for the real gap.
      if (feasibleScale < aiScale) {
        for (const ri of recipeIngredients) {
          const perUnit  = ri.quantityGrams * wastageMult;
          if (perUnit <= 0) continue;
          const wanted   = perUnit * aiScale;
          const have     = remainingStock.get(ri.ingredientId) ?? 0;
          const gap      = Math.round((wanted - have) * 10) / 10;
          if (gap > 0.05) {
            stockShortfalls.push({
              ingredientId:   ri.ingredientId,
              ingredientName: ri.name,
              shortfallGrams: gap,
              urgency:        "HIGH",
            });
          }
        }
      }

      // Apply the clamp to the batch the AI proposed.
      const clampRatio = aiScale > 0 ? feasibleScale / aiScale : 0;
      const scale      = feasibleScale;
      const clampedQty = Math.max(0, Math.round(aiQty * clampRatio));

      // Nothing can be made with current stock → skip this batch entirely,
      // but the shortfall above is already recorded so procurement fires.
      if (scale <= 0 || clampedQty <= 0) {
        continue;
      }

      // Decrement remaining stock by what this (clamped) batch will consume so
      // later batches sharing an ingredient see the depleted amount.
      for (const ri of recipeIngredients) {
        const consumed = ri.quantityGrams * wastageMult * scale;
        remainingStock.set(ri.ingredientId, (remainingStock.get(ri.ingredientId) ?? 0) - consumed);
      }

      const createdBatch = await db.productionBatch.create({
        data: {
          scheduleId:       schedule.id,
          recipeId:         resolvedRecipeId,
          shiftType:        shiftType as any,
          status:           "SCHEDULED",
          quantity:         clampedQty,
          scaleFactor:      scale,
          plannedStartTime: new Date(batch.plannedStartTime),
          plannedEndTime:   new Date(batch.plannedEndTime),
          ovenSlots:        batch.ovenSlots,
        },
      });

      const steps = batch.checklistSteps ?? [];
      const stepDescriptions = steps.map((s) => typeof s === "string" ? s : s.description);

      // Fast lookups for validation.
      const recipeIngredientById = new Map(recipeIngredients.map((ri) => [ri.ingredientId, ri]));
      // Scaled recipe total per ingredient — the hard ceiling nothing may exceed.
      const scaledTotalById = new Map(
        recipeIngredients.map((ri) => [ri.ingredientId, ri.quantityGrams * scale])
      );

      // stepIdx → deductions attached to that step
      const stepDeductionMap = new Map<number, Array<{ ingredientId: string; grams: number; name: string }>>();
      // Running total already assigned per ingredient, so we never exceed the recipe amount.
      const assignedById = new Map<string, number>();

      // ── PRIMARY PATH: use the AI's structured per-step deductions ───────────
      // The planner is instructed to return, for every step, exactly which
      // ingredients it consumes and how many grams (already scaled for the batch).
      // We trust that structure but VALIDATE it: only known recipe ingredients,
      // and never more than the scaled recipe total for any ingredient.
      let usedStructured = false;
      steps.forEach((s, idx) => {
        if (typeof s === "string" || !Array.isArray(s.deductions)) return;
        for (const d of s.deductions) {
          const ri = recipeIngredientById.get(d.ingredientId);
          if (!ri) continue;                       // ignore ingredients not in this recipe
          const grams = Number(d.grams);
          if (!Number.isFinite(grams) || grams <= 0) continue;

          const cap        = scaledTotalById.get(d.ingredientId) ?? grams;
          const already    = assignedById.get(d.ingredientId) ?? 0;
          const remaining  = Math.max(0, cap - already);
          const applied    = Math.min(grams, remaining);
          if (applied <= 0) continue;              // this ingredient is already fully assigned

          assignedById.set(d.ingredientId, already + applied);
          const arr = stepDeductionMap.get(idx) ?? [];
          arr.push({ ingredientId: d.ingredientId, grams: Math.round(applied * 10) / 10, name: ri.name });
          stepDeductionMap.set(idx, arr);
          usedStructured = true;
        }
      });

      // ── FALLBACK PATH: no structured deductions → keyword-match step text ───
      // Only runs when the AI omitted structured data entirely for this batch.
      if (!usedStructured) {
        function stepMentions(desc: string, ri: { name: string }): boolean {
          const descLower  = desc.toLowerCase();
          const nameLower  = ri.name.toLowerCase();
          const simpleName = nameLower.split(" (")[0].trim();
          const coreName   = simpleName.replace(/\s*\d+%.*/, "").trim();
          return descLower.includes(nameLower)
            || descLower.includes(simpleName)
            || (coreName.length > 3 && descLower.includes(coreName));
        }

        const claimedSpans = new Map<number, string[]>();
        const sortedIngredients = [...recipeIngredients].sort((a, b) => b.name.length - a.name.length);

        for (const ri of sortedIngredients) {
          const totalGrams = ri.quantityGrams * scale;
          const matchingSteps = stepDescriptions
            .map((desc, i) => ({ desc, i }))
            .filter(({ desc, i }) => {
              if (!stepMentions(desc, ri)) return false;
              const claimed = claimedSpans.get(i) ?? [];
              const nameLower = ri.name.toLowerCase().split(" (")[0].trim();
              if (claimed.some((c) => c.includes(nameLower))) return false;
              claimed.push(nameLower);
              claimedSpans.set(i, claimed);
              return true;
            })
            .map(({ i }) => i);

          if (matchingSteps.length === 0) continue;

          const perStep = totalGrams / matchingSteps.length;
          matchingSteps.forEach((stepIdx) => {
            assignedById.set(ri.ingredientId, (assignedById.get(ri.ingredientId) ?? 0) + perStep);
            const arr = stepDeductionMap.get(stepIdx) ?? [];
            arr.push({ ingredientId: ri.ingredientId, grams: Math.round(perStep * 10) / 10, name: ri.name });
            stepDeductionMap.set(stepIdx, arr);
          });
        }
      }

      // ── RECONCILIATION: never silently under-deduct ─────────────────────────
      // If any recipe ingredient was not fully assigned across the steps (AI
      // forgot it, or named it differently), attach the remainder so the batch's
      // stock consumption always matches the true recipe. We pin the remainder to
      // the first step whose text mentions the ingredient, else the first step.
      for (const ri of recipeIngredients) {
        const cap       = ri.quantityGrams * scale;
        const assigned  = assignedById.get(ri.ingredientId) ?? 0;
        const remainder = Math.round((cap - assigned) * 10) / 10;
        if (remainder <= 0.05) continue;           // fully (or close-enough) assigned

        const nameLower = ri.name.toLowerCase().split(" (")[0].trim();
        let targetIdx = stepDescriptions.findIndex((d) => d.toLowerCase().includes(nameLower));
        if (targetIdx === -1) targetIdx = 0;

        const arr = stepDeductionMap.get(targetIdx) ?? [];
        const existing = arr.find((a) => a.ingredientId === ri.ingredientId);
        if (existing) {
          existing.grams = Math.round((existing.grams + remainder) * 10) / 10;
        } else {
          arr.push({ ingredientId: ri.ingredientId, grams: remainder, name: ri.name });
        }
        stepDeductionMap.set(targetIdx, arr);
      }

      // PASS 2: create checklist items + their deductions
      for (let idx = 0; idx < stepDescriptions.length; idx++) {
        const description = stepDescriptions[idx];

        const createdItem = await db.checklistItem.create({
          data: {
            batchId:     createdBatch.id,
            order:       idx + 1,
            description: description,
            status:      "PENDING",
          },
        });

        const stepDeductions = stepDeductionMap.get(idx) ?? [];

        if (stepDeductions.length > 0) {
          await db.checklistDeduction.createMany({
            data: stepDeductions.map((d) => ({
              checklistItemId: createdItem.id,
              ingredientId:    d.ingredientId,
              deductionGrams:  d.grams,
            })),
          });
          // NOTE: we keep the AI's original step description as-is. It already
          // contains full ingredient names + quantities (per the planner prompt),
          // and the exact per-ingredient amounts are surfaced separately as the
          // deduction chips in the floor-staff UI. We no longer overwrite the
          // instruction text, which previously mangled clear steps into "Use …".
        }
      }

      // ── 3. Collect shortfalls ──────────────────────────────────────────────
      for (const req of batch.ingredientRequirements) {
        if (req.shortfallGrams > 0) {
          const urgency =
            req.shortfallGrams >= req.requiredGrams * 0.5 ? "CRITICAL" :
            req.shortfallGrams >= req.requiredGrams * 0.25 ? "HIGH" :
            req.shortfallGrams >= req.requiredGrams * 0.1  ? "MEDIUM" :
            "LOW";

          shortfalls.push({
            ingredientId:   req.ingredientId,
            ingredientName: req.name,
            shortfallGrams: req.shortfallGrams,
            urgency,
          });
        }
      }
    }

    // ── 4. Deduplicate shortfalls and create ProcurementRecommendations ──────
    // Merge the AI-reported shortfalls with the deterministic ones the stock
    // guardrail detected (the real gap between what was planned and what stock
    // could cover), so procurement is raised for actual shortfalls, not just
    // whatever the AI happened to report.
    const uniqueShortfalls = deduplicateShortfalls([...shortfalls, ...stockShortfalls]);

    for (const s of uniqueShortfalls) {
      const ingredient = await db.ingredient.findUnique({
        where:   { id: s.ingredientId },
        include: { supplier: true },
      });
      if (!ingredient) continue;

      // Check if there's already an unapproved recommendation for this ingredient
      const existing = await db.procurementRecommendation.findFirst({
        where: {
          bakeryId,
          ingredientId: s.ingredientId,
          approvedAt:   null,
          dismissedAt:  null,
        },
      });

      const currentStock    = Number(ingredient.stockGrams);
      const estimatedCost   = Number(ingredient.costPerKg) > 0
        ? (s.shortfallGrams / 1000) * Number(ingredient.costPerKg)
        : null;

      if (existing) {
        // Update urgency and shortfall on existing recommendation
        await db.procurementRecommendation.update({
          where: { id: existing.id },
          data: {
            shortfallGrams:        s.shortfallGrams,
            recommendedOrderGrams: s.shortfallGrams * 1.2, // 20% buffer
            urgency:               s.urgency,
            estimatedCost,
          },
        });
      } else {
        await db.procurementRecommendation.create({
          data: {
            bakeryId,
            ingredientId:          s.ingredientId,
            currentStockGrams:     currentStock,
            requiredGrams:         currentStock + s.shortfallGrams,
            shortfallGrams:        s.shortfallGrams,
            recommendedOrderGrams: s.shortfallGrams * 1.2,
            supplierId:            ingredient.supplierId,
            estimatedCost,
            urgency:               s.urgency,
          },
        });
      }

      // Create an alert for CRITICAL/HIGH shortfalls
      if (s.urgency === "CRITICAL" || s.urgency === "HIGH") {
        await db.agentAlert.create({
          data: {
            bakeryId,
            type:     "SHORTFALL",
            severity: s.urgency === "CRITICAL" ? "CRITICAL" : "WARNING",
            title:    `${s.urgency === "CRITICAL" ? "Critical" : "Low"} stock: ${s.ingredientName}`,
            message:  `${s.shortfallGrams.toFixed(0)}g shortfall for ${format(scheduleDate, "dd MMM")} ` +
                      `${shiftType.toLowerCase()} shift production. ` +
                      `Current stock: ${currentStock.toFixed(0)}g. ` +
                      `Recommended order: ${(s.shortfallGrams * 1.2).toFixed(0)}g.`,
            relatedEntityId:   s.ingredientId,
            relatedEntityType: "Ingredient",
          },
        });
      }
    }

    // ── 5. Create alerts for AI warnings ────────────────────────────────────
    // Dedup: don't raise a planning note that's already open with the same
    // message (regenerating a schedule while a problem persists would otherwise
    // stack identical warnings).
    for (const warning of plan.warnings) {
      const existing = await db.agentAlert.findFirst({
        where: {
          bakeryId,
          type:        "DELAY",
          title:       "Production planning note",
          message:     warning,
          isDismissed: false,
        },
      });
      if (existing) continue;

      await db.agentAlert.create({
        data: {
          bakeryId,
          type:     "DELAY",
          severity: "WARNING",
          title:    "Production planning note",
          message:  warning,
        },
      });
    }

    // ── 6. Mark the AgentAction as completed ────────────────────────────────
    const processingMs = Date.now() - startedAt.getTime();
    await db.agentAction.update({
      where: { id: agentActionId },
      data: {
        status:      "COMPLETED",
        completedAt: new Date(),
        details: {
          scheduleId:      schedule.id,
          batchCount:      plan.batches.length,
          shortfallCount:  uniqueShortfalls.length,
          processingMs,
        },
      },
    });

    return {
      success:      true,
      scheduleId:   schedule.id,
      shortfalls:   uniqueShortfalls,
      warnings:     plan.warnings,
      aiNotes:      plan.aiNotes,
      processingMs,
    };

  } catch (err) {
    // Mark action as failed
    await db.agentAction.update({
      where: { id: agentActionId },
      data: {
        status:       "FAILED",
        completedAt:  new Date(),
        errorMessage: err instanceof Error ? err.message : String(err),
      },
    });

    throw err;
  }
}

// ─── Helper: sum shortfalls for the same ingredient across multiple batches ───

function deduplicateShortfalls(
  shortfalls: AgentRunResult["shortfalls"]
): AgentRunResult["shortfalls"] {
  const map = new Map<string, AgentRunResult["shortfalls"][0]>();

  for (const s of shortfalls) {
    const existing = map.get(s.ingredientId);
    if (existing) {
      const total = existing.shortfallGrams + s.shortfallGrams;
      const urgency =
        total >= 5000  ? "CRITICAL" :
        total >= 2000  ? "HIGH" :
        total >= 500   ? "MEDIUM" :
        "LOW";
      map.set(s.ingredientId, { ...existing, shortfallGrams: total, urgency });
    } else {
      map.set(s.ingredientId, { ...s });
    }
  }

  return Array.from(map.values());
}
