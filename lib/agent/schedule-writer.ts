/**
 * lib/agent/schedule-writer.ts
 *
 * Takes the AgentSchedulePlan from the planner and persists it to the database:
 *  1. Creates/updates ProductionSchedule
 *  2. Creates ProductionBatch rows with ovenSlots + scaleFactor
 *  3. Creates ChecklistItem rows from checklistSteps
 *  4. Creates ProcurementRecommendation rows for any ingredient shortfalls
 *  5. Creates AgentAlert rows for shortfalls, expiring lots, and warnings
 *
 * Does NOT deduct stock here — stock is deducted when a batch is marked
 * IN_PROGRESS by floor staff so the numbers stay accurate in real-time.
 */

import { db } from "@/lib/db";
import { format } from "date-fns";
import type { AgentBakeryContext, AgentSchedulePlan, AgentRunResult } from "./types";

export async function writeSchedule(
  context: AgentBakeryContext,
  plan: AgentSchedulePlan,
  agentActionId: string,
  startedAt: Date
): Promise<AgentRunResult> {
  const { bakeryId, targetDate, shiftType } = context;

  // Convert target date string back to a Date (midnight UTC)
  const scheduleDate = new Date(`${targetDate}T00:00:00.000Z`);

  const shortfalls: AgentRunResult["shortfalls"] = [];

  try {
    // ── 1. Upsert the ProductionSchedule ────────────────────────────────────
    const schedule = await db.productionSchedule.upsert({
      where: {
        bakeryId_scheduleDate_shiftType: {
          bakeryId,
          scheduleDate,
          shiftType: shiftType as any,
        },
      },
      update: {
        isAutoGenerated:             true,
        isApproved:                  false,  // reset approval on regeneration
        approvedById:                null,
        approvedAt:                  null,
        totalOvenUtilizationPercent: plan.ovenUtilizationPercent,
        aiNotes:                     plan.aiNotes,
        updatedAt:                   new Date(),
      },
      create: {
        bakeryId,
        scheduleDate,
        shiftType:                   shiftType as any,
        isAutoGenerated:             true,
        isApproved:                  false,
        totalOvenUtilizationPercent: plan.ovenUtilizationPercent,
        aiNotes:                     plan.aiNotes,
      },
    });

    // Delete any existing batches for this schedule (clean regeneration)
    await db.productionBatch.deleteMany({ where: { scheduleId: schedule.id } });

    // Build a lookup map: recipeId AND recipe name → actual DB recipeId
    const recipeMap = new Map<string, string>();
    for (const r of context.recipes) {
      recipeMap.set(r.recipeId, r.recipeId);
      recipeMap.set(r.name.toLowerCase(), r.recipeId);
    }

    // ── 2. Create batches + checklists ───────────────────────────────────────
    for (const batch of plan.batches) {
      // Resolve recipe ID — AI might return the actual ID or the recipe name
      const resolvedRecipeId = recipeMap.get(batch.recipeId)
        ?? recipeMap.get(batch.recipeName?.toLowerCase() ?? "")
        ?? null;

      if (!resolvedRecipeId) {
        // Skip batches with unrecognized recipes
        continue;
      }

      const createdBatch = await db.productionBatch.create({
        data: {
          scheduleId:       schedule.id,
          recipeId:         resolvedRecipeId,
          shiftType:        shiftType as any,
          status:           "SCHEDULED",
          quantity:         Math.round(batch.quantity),
          scaleFactor:      batch.scaleFactor,
          plannedStartTime: new Date(batch.plannedStartTime),
          plannedEndTime:   new Date(batch.plannedEndTime),
          ovenSlots:        batch.ovenSlots,
        },
      });

      // Build a set of valid ingredient IDs for this bakery (to validate AI output)
      const validIngredientIds = new Set(context.stockLevels.map((s) => s.ingredientId));

      // Create checklist items from the AI-generated steps, with deductions
      if (batch.checklistSteps.length > 0) {
        for (let idx = 0; idx < batch.checklistSteps.length; idx++) {
          const step = batch.checklistSteps[idx];

          // Handle both old (string) and new (object) formats safely
          const description = typeof step === "string" ? step : step.description;
          const deductions  = typeof step === "string" ? [] : (step.deductions ?? []);

          const createdItem = await db.checklistItem.create({
            data: {
              batchId:     createdBatch.id,
              order:       idx + 1,
              description: description,
              status:      "PENDING",
            },
          });

          // Create deduction entries — only for valid ingredients with positive grams
          const validDeductions = deductions.filter(
            (d) => d.ingredientId && validIngredientIds.has(d.ingredientId) && d.grams > 0
          );

          if (validDeductions.length > 0) {
            await db.checklistDeduction.createMany({
              data: validDeductions.map((d) => ({
                checklistItemId: createdItem.id,
                ingredientId:    d.ingredientId,
                deductionGrams:  d.grams,
              })),
            });
          }
        }
      }

      // ── 3. Collect shortfalls ──────────────────────────────────────────────
      for (const req of batch.ingredientRequirements) {
        if (req.shortfallGrams > 0) {
          const urgency =
            req.shortfallGrams >= req.requiredGrams * 0.5 ? "CRITICAL" :
            req.shortfallGrams >= req.requiredGrams * 0.25 ? "HIGH" :
            req.shortfallGrams >= req.requiredGrams * 0.1  ? "MEDIUM" :
            "LOW";

          shortfalls.push({
            ingredientId:   req.ingredientId,
            ingredientName: req.name,
            shortfallGrams: req.shortfallGrams,
            urgency,
          });
        }
      }
    }

    // ── 4. Deduplicate shortfalls and create ProcurementRecommendations ──────
    const uniqueShortfalls = deduplicateShortfalls(shortfalls);

    for (const s of uniqueShortfalls) {
      const ingredient = await db.ingredient.findUnique({
        where:   { id: s.ingredientId },
        include: { supplier: true },
      });
      if (!ingredient) continue;

      // Check if there's already an unapproved recommendation for this ingredient
      const existing = await db.procurementRecommendation.findFirst({
        where: {
          bakeryId,
          ingredientId: s.ingredientId,
          approvedAt:   null,
          dismissedAt:  null,
        },
      });

      const currentStock    = Number(ingredient.stockGrams);
      const estimatedCost   = Number(ingredient.costPerKg) > 0
        ? (s.shortfallGrams / 1000) * Number(ingredient.costPerKg)
        : null;

      if (existing) {
        // Update urgency and shortfall on existing recommendation
        await db.procurementRecommendation.update({
          where: { id: existing.id },
          data: {
            shortfallGrams:        s.shortfallGrams,
            recommendedOrderGrams: s.shortfallGrams * 1.2, // 20% buffer
            urgency:               s.urgency,
            estimatedCost,
          },
        });
      } else {
        await db.procurementRecommendation.create({
          data: {
            bakeryId,
            ingredientId:          s.ingredientId,
            currentStockGrams:     currentStock,
            requiredGrams:         currentStock + s.shortfallGrams,
            shortfallGrams:        s.shortfallGrams,
            recommendedOrderGrams: s.shortfallGrams * 1.2,
            supplierId:            ingredient.supplierId,
            estimatedCost,
            urgency:               s.urgency,
          },
        });
      }

      // Create an alert for CRITICAL/HIGH shortfalls
      if (s.urgency === "CRITICAL" || s.urgency === "HIGH") {
        await db.agentAlert.create({
          data: {
            bakeryId,
            type:     "SHORTFALL",
            severity: s.urgency === "CRITICAL" ? "CRITICAL" : "WARNING",
            title:    `${s.urgency === "CRITICAL" ? "Critical" : "Low"} stock: ${s.ingredientName}`,
            message:  `${s.shortfallGrams.toFixed(0)}g shortfall for ${format(scheduleDate, "dd MMM")} ` +
                      `${shiftType.toLowerCase()} shift production. ` +
                      `Current stock: ${currentStock.toFixed(0)}g. ` +
                      `Recommended order: ${(s.shortfallGrams * 1.2).toFixed(0)}g.`,
            relatedEntityId:   s.ingredientId,
            relatedEntityType: "Ingredient",
          },
        });
      }
    }

    // ── 5. Create alerts for AI warnings ────────────────────────────────────
    for (const warning of plan.warnings) {
      await db.agentAlert.create({
        data: {
          bakeryId,
          type:     "DELAY",
          severity: "WARNING",
          title:    "Production planning note",
          message:  warning,
        },
      });
    }

    // ── 6. Mark the AgentAction as completed ────────────────────────────────
    const processingMs = Date.now() - startedAt.getTime();
    await db.agentAction.update({
      where: { id: agentActionId },
      data: {
        status:      "COMPLETED",
        completedAt: new Date(),
        details: {
          scheduleId:      schedule.id,
          batchCount:      plan.batches.length,
          shortfallCount:  uniqueShortfalls.length,
          processingMs,
        },
      },
    });

    return {
      success:      true,
      scheduleId:   schedule.id,
      shortfalls:   uniqueShortfalls,
      warnings:     plan.warnings,
      aiNotes:      plan.aiNotes,
      processingMs,
    };

  } catch (err) {
    // Mark action as failed
    await db.agentAction.update({
      where: { id: agentActionId },
      data: {
        status:       "FAILED",
        completedAt:  new Date(),
        errorMessage: err instanceof Error ? err.message : String(err),
      },
    });

    throw err;
  }
}

// ─── Helper: sum shortfalls for the same ingredient across multiple batches ───

function deduplicateShortfalls(
  shortfalls: AgentRunResult["shortfalls"]
): AgentRunResult["shortfalls"] {
  const map = new Map<string, AgentRunResult["shortfalls"][0]>();

  for (const s of shortfalls) {
    const existing = map.get(s.ingredientId);
    if (existing) {
      const total = existing.shortfallGrams + s.shortfallGrams;
      const urgency =
        total >= 5000  ? "CRITICAL" :
        total >= 2000  ? "HIGH" :
        total >= 500   ? "MEDIUM" :
        "LOW";
      map.set(s.ingredientId, { ...existing, shortfallGrams: total, urgency });
    } else {
      map.set(s.ingredientId, { ...s });
    }
  }

  return Array.from(map.values());
}
